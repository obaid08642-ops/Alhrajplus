const KEY = "hp_lang";
const SUPPORTED = ["ar", "en", "hi", "ur", "bn", "fr"];
let _currentLang = "ar";
export function currentLang() { return _currentLang; }

// Global translator for utility files (helpers, axios interceptors, etc.) that
// can't use the useI18n() hook. Falls back to the original Arabic key if no
// translation is found — same behavior as t() inside components.
export function tr(key) {
    if (_currentLang === "ar") return key;
    return (STRINGS[_currentLang] && STRINGS[_currentLang][key]) || key;
}

export function I18nProvider({ children }) {
    const [lang, setLangState] = useState("ar");

    useEffect(() => {
        (async () => {
            const saved = await AsyncStorage.getItem(KEY);
            if (saved && SUPPORTED.includes(saved)) {
                setLangState(saved);
                _currentLang = saved;
                // Make sure the layout direction matches the persisted language
                // even when the system locale differs from the user choice.
                const wantRTL = (saved === "ar" || saved === "ur");
                try {
                    if (I18nManager.isRTL !== wantRTL) {
                        I18nManager.allowRTL(wantRTL);
                        I18nManager.forceRTL(wantRTL);
                    }
                } catch (_) {}
            }
        })();
    }, []);

    const setLang = useCallback(async (l) => {
        if (!SUPPORTED.includes(l)) return;
        setLangState(l);
        _currentLang = l;
        await AsyncStorage.setItem(KEY, l);
        try {
            const wantRTL = (l === "ar" || l === "ur");
            if (I18nManager.isRTL !== wantRTL) {
                I18nManager.allowRTL(wantRTL);
                I18nManager.forceRTL(wantRTL);
                // RN requires a JS-bundle reload for the new direction to take
                // effect on all already-mounted views. Use expo-updates when
                // available — otherwise fall back to a soft React remount.
                try {
                    const Updates = require("expo-updates");
                    if (Updates && typeof Updates.reloadAsync === "function") {
                        await Updates.reloadAsync();
                    }
                } catch (_) { /* dev / non-managed build — UI will repaint on next nav */ }
            }
        } catch (_) {}
    }, []);

    // Translate by canonical Arabic key. Pass-through for ar; fall back to key itself.
    const t = useCallback((key) => {
        if (!key) return key;
        if (lang === "ar") return key;
        const table = STRINGS[lang];
        return (table && table[key]) || key;
    }, [lang]);

    return <I18nCtx.Provider value={{ lang, setLang, t, supported: SUPPORTED }}>
        {/* `key={lang}` triggers a SOFT remount of the entire tree whenever
            the user picks a new language. This forces every screen to
            re-render with the new translations + RTL/LTR direction without
            requiring a native app reload (Expo Go-safe). */}
        <View style={{ flex: 1 }} key={lang}>{children}</View>
    </I18nCtx.Provider>;
}

export const useI18n = () => useContext(I18nCtx) || { lang: "ar", setLang: () => {}, t: (k) => k, supported: SUPPORTED };
